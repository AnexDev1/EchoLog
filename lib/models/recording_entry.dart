import 'package:flutter/material.dart';
import 'package:hive/hive.dart';

part 'recording_entry.g.dart'; // This will be generated by build_runner

@HiveType(typeId: 1) // Ensure this typeId is unique across your Hive models
class RecordingEntry extends HiveObject {
  @HiveField(0)
  late String id;

  @HiveField(1)
  late String filePath;

  @HiveField(2)
  late String displayName;

  @HiveField(3)
  late Duration duration;

  @HiveField(4)
  late DateTime dateRecorded;

  @HiveField(5)
  late String moodName;

  @HiveField(6)
  late Color moodColor;

  @HiveField(7)
  late Color moodIconColor;

  @HiveField(8)
  late String moodEmoji;

  @HiveField(9)
  String? transcription;

  @HiveField(10)
  List<double>? waveformPoints;

  @HiveField(11)
  String? summaryPreview;

  @HiveField(12)
  bool isPlaying;

  RecordingEntry({
    required this.id,
    required this.filePath,
    required this.displayName,
    required this.duration,
    required this.dateRecorded,
    required this.moodName,
    required this.moodColor,
    required this.moodIconColor,
    required this.moodEmoji,
    this.transcription,
    this.waveformPoints,
    this.summaryPreview,
    this.isPlaying = false,
  });

  Map<String, dynamic> toJson() {
    return {
      'id': id,
      'filePath': filePath,
      'displayName': displayName,
      'duration': duration.inMilliseconds,
      'dateRecorded': dateRecorded.toIso8601String(),
      'moodName': moodName,
      'moodColor': moodColor.value,
      'moodIconColor': moodIconColor.value,
      'moodEmoji': moodEmoji,
      'transcription': transcription,
      'waveformPoints': waveformPoints,
      'summaryPreview': summaryPreview,
      'isPlaying': isPlaying,
    };
  }

  factory RecordingEntry.fromJson(Map<String, dynamic> json) {
    return RecordingEntry(
      id: json['id'] as String,
      filePath: json['filePath'] as String,
      displayName: json['displayName'] as String,
      duration: Duration(milliseconds: json['duration'] as int),
      dateRecorded: DateTime.parse(json['dateRecorded'] as String),
      moodName: json['moodName'] as String,
      moodColor: Color(json['moodColor'] as int),
      moodIconColor: Color(json['moodIconColor'] as int),
      moodEmoji: json['moodEmoji'] as String,
      transcription: json['transcription'] as String?,
      waveformPoints: (json['waveformPoints'] as List<dynamic>?)
          ?.map((e) => (e as num).toDouble())
          .toList(),
      summaryPreview: json['summaryPreview'] as String?,
      isPlaying: json['isPlaying'] as bool? ?? false,
    );
  }
}

