import 'package:echolog/utils/color_adapter.dart';
import 'package:flutter/material.dart';
import 'package:hive/hive.dart';

part 'recording_entry.g.dart'; // This will be generated by build_runner

@HiveType(typeId: 1) // Ensure this typeId is unique across your Hive models
class RecordingEntry extends HiveObject {
  @HiveField(0)
  late String id;

  @HiveField(1)
  late String filePath;

  @HiveField(2)
  late String displayName;

  @HiveField(3)
  late Duration duration;

  @HiveField(4)
  late DateTime dateRecorded;

  @HiveField(5)
  late String moodName;

  @HiveField(6)
  late Color moodColor;

  @HiveField(7)
  late Color moodIconColor;

  @HiveField(8)
  late String moodEmoji;

  @HiveField(9)
  String? transcription; // Existing field

  @HiveField(10)
  List<double>? waveformPoints; // NEW: For mini waveform preview

  @HiveField(11)
  String? summaryPreview; // NEW: For AI summary/transcript preview

  // This field is primarily for UI state and might not always be persisted
  // or could be handled differently. If you persist it, ensure it's reset appropriately.
  @HiveField(12)
  bool isPlaying;

  RecordingEntry({
    required this.id,
    required this.filePath,
    required this.displayName,
    required this.duration,
    required this.dateRecorded,
    required this.moodName,
    required this.moodColor,
    required this.moodIconColor,
    required this.moodEmoji,
    this.transcription,
    this.waveformPoints, // Added to constructor
    this.summaryPreview, // Added to constructor
    this.isPlaying = false,
  });

  // Optional: toMap and fromMap for other uses (e.g., debugging, other databases)
  Map<String, dynamic> toMap() {
    return {
      'id': id,
      'filePath': filePath,
      'displayName': displayName,
      'duration': duration.inMilliseconds,
      'dateRecorded': dateRecorded.toIso8601String(),
      'moodName': moodName,
      'moodColor': moodColor.value, // Store as int
      'moodIconColor': moodIconColor.value, // Store as int
      'moodEmoji': moodEmoji,
      'transcription': transcription,
      'waveformPoints': waveformPoints,
      'summaryPreview': summaryPreview,
      'isPlaying': isPlaying,
    };
  }

  factory RecordingEntry.fromMap(Map<String, dynamic> map) {
    return RecordingEntry(
      id: map['id'] as String,
      filePath: map['filePath'] as String,
      displayName: map['displayName'] as String,
      duration: Duration(milliseconds: map['duration'] as int),
      dateRecorded: DateTime.parse(map['dateRecorded'] as String),
      moodName: map['moodName'] as String,
      moodColor: Color(map['moodColor'] as int),
      moodIconColor: Color(map['moodIconColor'] as int),
      moodEmoji: map['moodEmoji'] as String,
      transcription: map['transcription'] as String?,
      waveformPoints: (map['waveformPoints'] as List<dynamic>?)
          ?.map((e) => (e as num).toDouble())
          .toList(),
      summaryPreview: map['summaryPreview'] as String?,
      isPlaying: map['isPlaying'] as bool? ?? false,
    );
  }
}

